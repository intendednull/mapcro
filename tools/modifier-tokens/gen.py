"""Generate crates/replay/src/modifiers.rs from a boon-data modifiers.json (a catalog snapshot
derived from the game's modifier definitions; docs/research/status-effects.md section 3).

    python3 -I tools/modifier-tokens/gen.py <modifiers.json> > crates/replay/src/modifiers.rs

Writes only CUtlStringToken ids: no names, strings or art from the game."""
import json, sys

M = 0x5BD1E995


def token(s):
    k = s.lower().encode()
    h = (0x31415926 ^ len(k)) & 0xFFFFFFFF
    i = 0
    while len(k) - i >= 4:
        x = int.from_bytes(k[i:i + 4], "little")
        x = (x * M) & 0xFFFFFFFF
        x ^= x >> 24
        x = (x * M) & 0xFFFFFFFF
        h = ((h * M) & 0xFFFFFFFF) ^ x
        i += 4
    r = k[i:]
    if len(r) >= 3:
        h ^= r[2] << 16
    if len(r) >= 2:
        h ^= r[1] << 8
    if len(r) >= 1:
        h ^= r[0]
        h = (h * M) & 0xFFFFFFFF
    h ^= h >> 13
    h = (h * M) & 0xFFFFFFFF
    h ^= h >> 15
    return h


# Keep in step with timeline::CC_STATES.
CC = [13, 14, 15, 17, 20, 59, 68, 81, 129]

m = json.load(open(sys.argv[1]))
states = {v: int(k) for k, v in m["modifier_states"].items()}
byname = {}


def walk(d):
    if isinstance(d, dict):
        if "_class" in d:
            byname.setdefault(d.get("_my_subclass_name") or d["_class"], d)
        for v in d.values():
            walk(v)
    elif isinstance(d, list):
        for v in d:
            walk(v)


for r in m["records"]:
    walk(r["definition"])


def get(d, f, depth=0):
    if f in d or depth > 6:
        return d.get(f)
    b = d.get("_base") or d.get("_class")
    nb = byname.get(b) if b else None
    if nb is None or nb is d:
        return None
    return get(nb, f, depth + 1)


icons, cc = set(), {}
for rec in m["records"]:
    d = rec["definition"] or {}
    leaf = rec["qualified_modifier_name"].split("/")[-1]
    dd = byname.get(leaf, d) or d
    ids = (rec["qualified_modifier_id"], rec["modifier_id"])
    if get(dd, "m_strSmallIconCssClass") or get(dd, "m_strHudIcon"):
        icons.update(ids)
    mask = get(dd, "m_nEnabledStateMask")
    if isinstance(mask, str):
        bits = 0
        for name in mask.split("|"):
            i = states.get(name.strip())
            if i in CC:
                bits |= 1 << CC.index(i)
        if bits:
            for t in ids:
                cc[t] = cc.get(t, 0) | bits

# The generic CC modifiers are engine modifiers: the catalog has their names but no definition
# to read a state mask from. They carry the real cause in the demo (status-effects.md section 2),
# so they're listed by hand, by state.
GENERIC = {
    20: ["modifier_citadel_stunned", "modifier_citadel_stunned_no_cc_diminish", "modifier_citadel_knockdown", "modifier_citadel_tossup", "modifier_citadel_parried_stun", "modifier_citadel_catapult_damage_stun"],
    17: ["modifier_citadel_silenced"],
    81: ["modifier_citadel_sleep"],
    15: ["modifier_citadel_muted"],
    14: ["modifier_citadel_disarmed"],
    68: ["modifier_citadel_disarmed"],
    13: ["modifier_citadel_root"],
}
for state, names in GENERIC.items():
    for n in names:
        t = token(n)
        cc[t] = cc.get(t, 0) | (1 << CC.index(state))

print(f"""//! Generated by tools/modifier-tokens/gen.py from boon-data's modifiers catalog (client
//! {m['client_version']}, commit {m['source_commit'][:12]}). Token ids only. Regenerate when a patch adds
//! modifiers: an effect missing here isn't stored (docs/research/status-effects.md §3).

/// Modifiers the game shows an icon for (`m_strSmallIconCssClass` or `m_strHudIcon`), sorted.
pub const ICON_MODIFIERS: [u32; {len(icons)}] = [""")
for t in sorted(icons):
    print(f"    {t},")
print("];\n")
print(f"""/// Modifiers whose definition sets hard-CC states: `(token, bits)`, bit i = `CC_STATES[i]`,
/// sorted by token.
pub const CC_MODIFIERS: [(u32, u16); {len(cc)}] = [""")
for t in sorted(cc):
    print(f"    ({t}, {cc[t]}),")
print("];")
