// Regenerates src/map/fallback-data.ts from design/shared/minimap-data.js (our own derived
// coordinates, MIT; no art). The fallback map is what a board draws when its server has no asset
// pack: the same entity list a pack carries, so one code path renders both.
//   node web/scripts/fallback-from-design.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "../..");
const src = readFileSync(join(root, "design/shared/minimap-data.js"), "utf8");
const d = JSON.parse(src.slice(src.indexOf("{"), src.lastIndexOf("}") + 1));
const R = 10752;
// Percent of the map square back to world units (the inverse of the README's transform).
const world = (p) => [Math.round((p.x / 100) * 2 * R - R), Math.round(R - (p.y / 100) * 2 * R)];
const LANE = { yellow: "lane1", blue: "lane4", purple: "lane6" };
const KIND = { t1: "guardian", t2: "walker", t3: "patron", barracks: "base_guardian", shrine: "shrine", midboss: "mid_boss" };
const n = {};
const entities = [];
const add = (kind, team, lane, p, extra = {}) => {
  const base = `${kind}:${team}:${lane}`;
  n[base] = (n[base] ?? 0) + 1;
  entities.push({ key: `${base}:${n[base]}`, kind, team, lane, world: world(p), ...extra });
};
for (const o of d.objectives) add(KIND[o.k], o.team, LANE[o.lane] ?? "lane0", o);
for (const c of d.camps) if (c.t !== "midboss") add("camp", "neutral", "lane0", c, { tier: c.t });
add("rift", "neutral", "lane1", d.koth);
// The two powerup spawners (the pack's kind "powerup"), west then east.
for (const [i, pu] of d.powerups.entries()) add("powerup", "neutral", i === 0 ? "lane1" : "lane6", pu);
// The design shows the one active site; the map has two, mirrored across the centre (the
// extractor's pack lists both at x = ±7648). Either can be the active one on a board.
add("rift", "neutral", "lane6", { x: 100 - d.koth.x, y: d.koth.y });
const lanes = d.lanes.map((l) => ({ lane: l.lane, d: l.d }));
const out = `// Generated by web/scripts/fallback-from-design.mjs from design/shared/minimap-data.js. Do not edit.
// Map entities in world units (no art), for boards whose server has no asset pack.
import type { FallbackData } from "./model";

export const FALLBACK: FallbackData = ${JSON.stringify({ entities, lanes })};
`;
writeFileSync(join(root, "web/src/map/fallback-data.ts"), out);
console.log(`${entities.length} entities, ${lanes.length} lanes`);
